    D=M
    @LOOP
    D;JEQ

    @ptr
    A=M
    M=0

    @ptr
    A=M+1
    M=0

    @32
    D=A
    @ptr
    M=D+M

    @i
    M=M-1

    @CLEAR_LOOP
    0;JMP
