// Copia los 64 registros de la tabla (src) a la pantalla (ptr),
// saltando +32 por fila para bajar una linea en el framebuffer.
(COPY_GLYPH)
    @SCREEN
    D=A
    @ptr
    M=D
    @32
    D=A
    @i
    M=D

(COPY_GLYPH_LOOP)
    @i
    D=M
    @LOOP
    D;JEQ

    @src
    A=M
    D=M
    @ptr
    A=M
    M=D

    @src
    M=M+1
    A=M
    D=M
    @ptr
    A=M+1
    M=D

    @src
    M=M+1

    @32
    D=A
    @ptr
    M=D+M

    @i
    M=M-1

    @COPY_GLYPH_LOOP
    0;JMP

// Borra la matriz 32x32 escribiendo ceros con el mismo salto de +32.
